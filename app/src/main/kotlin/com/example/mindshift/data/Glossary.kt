    fun byId(id: String): GlossaryTerm? = all.firstOrNull { it.id == id }

    fun search(needle: String): List<GlossaryTerm> {
        val n = needle.trim().lowercase()
        if (n.isEmpty()) return emptyList()
        return all.filter {
            it.term.lowercase().contains(n) || it.definition.lowercase().contains(n)
        }
    }
